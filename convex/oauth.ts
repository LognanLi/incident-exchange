// Minimal OAuth 2.1 authorization server for agents (client_credentials grant, RFC 6749 §4.4) and token
// validation for the remote MCP endpoint (RFC 9728 protected resource). The client secret is the
// operator-issued agent credential (`ixa_…`); access tokens (`ixat_…`) are short-lived and audience-bound.
import { v } from "convex/values";
import { internalMutation, internalQuery } from "./_generated/server";
import { sha256Hex } from "../shared/bundle.mjs";

export const ACCESS_TOKEN_TTL_MS = 15 * 60 * 1000;

/** Verifies client credentials and stores the hash of an access token generated by the caller (an HTTP action). */
export const issue = internalMutation({
  args: { clientId: v.string(), clientSecret: v.string(), accessTokenHash: v.string(), audience: v.string(), scope: v.optional(v.string()) },
  handler: async (ctx, a) => {
    const p = await ctx.db.query("agentPrincipals").withIndex("by_name", (q) => q.eq("name", a.clientId)).unique();
    const secretHash = await sha256Hex(a.clientSecret);
    if (!p || p.tokenHash !== secretHash || p.revoked || p.expiresAt < Date.now()) return { error: "invalid_client" as const };
    const requested = a.scope ? a.scope.split(" ").filter(Boolean) : p.scopes;
    if (requested.some((s) => !p.scopes.includes(s))) return { error: "invalid_scope" as const };
    const expiresAt = Math.min(Date.now() + ACCESS_TOKEN_TTL_MS, p.expiresAt);
    await ctx.db.insert("oauthTokens", { principalId: p._id, tokenHash: a.accessTokenHash, audience: a.audience, scopes: requested, expiresAt, createdAt: Date.now() });
    // Opportunistic cleanup of this principal's expired tokens is unnecessary at demo scale; tokens expire in 15 min.
    return { scopes: requested, expiresIn: Math.floor((expiresAt - Date.now()) / 1000) };
  },
});

export const validate = internalQuery({
  args: { accessToken: v.string(), audience: v.string() },
  handler: async (ctx, { accessToken, audience }) => {
    if (!accessToken.startsWith("ixat_")) return { ok: false };
    const tokenHash = await sha256Hex(accessToken);
    const at = await ctx.db.query("oauthTokens").withIndex("by_tokenHash", (q) => q.eq("tokenHash", tokenHash)).unique();
    if (!at || at.expiresAt < Date.now() || at.audience !== audience) return { ok: false };
    const p = await ctx.db.get(at.principalId);
    return { ok: !!p && !p.revoked && p.expiresAt > Date.now(), principal: p?.name };
  },
});
